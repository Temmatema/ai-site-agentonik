export const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
export const isContact = (v) => {
  v = v.trim();
  if (/^@[\w]{4,}$/.test(v)) return true;
  if (/^[\w.+-]+@[\w-]+\.[\w.]+$/.test(v)) return true;
  return v.replace(/\D/g, '').length >= 10;
};
